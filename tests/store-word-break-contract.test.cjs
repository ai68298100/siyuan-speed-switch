const test=require('node:test');const assert=require('node:assert/strict');const fs=require('node:fs');const path=require('node:path');const css=fs.readFileSync(path.join(__dirname,'..','src','index.scss'),'utf8');
test('word break property exists',()=>assert.match(css,/word-break: break-word/));
test('title has word break fallback',()=>assert.match(css,/strong[\s\S]*?word-break: break-word/));
test('description has word break fallback',()=>assert.match(css,/span[\s\S]*?word-break: break-word/));
test('group has word break fallback',()=>assert.match(css,/\.sw-home-store__group[\s\S]*?word-break: break-word/));
test('summary has word break fallback',()=>assert.match(css,/\.sw-home-store__summary[\s\S]*?word-break: break-word/));
test('word break pairs with overflow wrap',()=>assert.match(css,/overflow-wrap: anywhere[\s\S]*?word-break: break-word/));
test('word break pairs with hyphens',()=>assert.match(css,/hyphens: auto/));
test('word break pairs with pretty wrap',()=>assert.match(css,/text-wrap: pretty/));
test('word break keeps mobile',()=>assert.match(css,/max-width: 560px/));
test('word break keeps print',()=>assert.match(css,/@media print/));
test('word break keeps high contrast',()=>assert.match(css,/forced-colors: active/));
test('word break keeps reduced motion',()=>assert.match(css,/prefers-reduced-motion: reduce/));
test('word break is standard CSS',()=>assert.match(css,/word-break/));
test('word break avoids url dependency',()=>assert.doesNotMatch(css,/word-break: break-word[\s\S]*?url\(/));
test('word break avoids script dependency',()=>assert.doesNotMatch(css,/word-break: break-word[\s\S]*?javascript/));
test('word break title remains block',()=>assert.match(css,/strong[\s\S]*?display: block/));
test('word break description remains clamped',()=>assert.match(css,/-webkit-line-clamp: 2/));
test('word break status remains visible',()=>assert.match(css,/\.sw-home-store__status/));
test('word break group remains visible',()=>assert.match(css,/\.sw-home-store__group/));
test('word break summary remains visible',()=>assert.match(css,/\.sw-home-store__summary/));
test('word break preserves title balance',()=>assert.match(css,/text-wrap: balance/));
test('word break preserves line height',()=>assert.match(css,/line-height: 1\.35/));
test('word break preserves font metrics',()=>assert.match(css,/font-size-adjust: from-font/));
test('word break preserves numeric metrics',()=>assert.match(css,/font-variant-numeric: tabular-nums/));
test('word break preserves focus',()=>assert.match(css,/focus-visible/));
test('word break preserves touch',()=>assert.match(css,/touch-action: manipulation/));
test('word break title scope',()=>assert.match(css,/sw-home-store__card-head/));
test('word break group scope',()=>assert.match(css,/sw-home-store__group/));
test('word break summary scope',()=>assert.match(css,/sw-home-store__summary/));
test('word break contract deterministic',()=>assert.ok(css.includes('word-break: break-word')&&css.includes('overflow-wrap: anywhere')));
