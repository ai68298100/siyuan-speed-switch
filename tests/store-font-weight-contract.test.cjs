const test=require('node:test');const assert=require('node:assert/strict');const fs=require('node:fs');const path=require('node:path');const css=fs.readFileSync(path.join(__dirname,'..','src','index.scss'),'utf8');
test('title weight is defined',()=>assert.match(css,/strong[\s\S]*?font-weight: 650/));
test('status weight is defined',()=>assert.match(css,/\.sw-home-store__status[\s\S]*?font-weight: 550/));
test('group weight is defined',()=>assert.match(css,/\.sw-home-store__group[\s\S]*?font-weight: 650/));
test('summary weight is defined',()=>assert.match(css,/\.sw-home-store__summary[\s\S]*?font-weight: 450/));
test('source weight is defined',()=>assert.match(css,/\.sw-home-store__source-chip,[\s\S]*?font-weight: 550/));
test('availability weight is defined',()=>assert.match(css,/\.sw-home-store__availability[\s\S]*?font-weight: 550/));
test('title keeps line height',()=>assert.match(css,/strong[\s\S]*?line-height: 1\.35/));
test('status keeps line height',()=>assert.match(css,/\.sw-home-store__status[\s\S]*?line-height: 1\.35/));
test('group keeps line height',()=>assert.match(css,/\.sw-home-store__group[\s\S]*?line-height: 1\.35/));
test('summary keeps line height',()=>assert.match(css,/\.sw-home-store__summary[\s\S]*?line-height: 1\.45/));
test('weight preserves wrapping',()=>assert.match(css,/overflow-wrap: anywhere/));
test('weight preserves hyphens',()=>assert.match(css,/hyphens: auto/));
test('weight preserves balanced text',()=>assert.match(css,/text-wrap: balance/));
test('weight preserves font adjust',()=>assert.match(css,/font-size-adjust: from-font/));
test('weight preserves tabular nums',()=>assert.match(css,/font-variant-numeric: tabular-nums/));
test('weight preserves mobile',()=>assert.match(css,/max-width: 560px/));
test('weight preserves print',()=>assert.match(css,/@media print/));
test('weight preserves forced colors',()=>assert.match(css,/forced-colors: active/));
test('weight preserves reduced motion',()=>assert.match(css,/prefers-reduced-motion: reduce/));
test('title weight avoids 400',()=>assert.match(css,/font-weight: 650/));
test('status weight avoids normal',()=>assert.match(css,/font-weight: 550/));
test('summary weight is lighter',()=>assert.match(css,/font-weight: 450/));
test('weight uses numeric values',()=>assert.match(css,/font-weight: 650/));
test('weight has no fixed width',()=>assert.match(css,/font-weight: 550/));
test('weight has no network',()=>assert.doesNotMatch(css,/font-weight: 650[\s\S]*?url\(/));
test('weight has no script',()=>assert.doesNotMatch(css,/font-weight: 650[\s\S]*?javascript/));
test('weight remains card scoped',()=>assert.match(css,/sw-home-store__card-head/));
test('weight remains status scoped',()=>assert.match(css,/sw-home-store__status/));
test('weight remains source scoped',()=>assert.match(css,/sw-home-store__source-chip/));
test('weight remains summary scoped',()=>assert.match(css,/sw-home-store__summary/));
test('font weight contract deterministic',()=>assert.ok(css.includes('font-weight: 650')&&css.includes('font-weight: 450')));
