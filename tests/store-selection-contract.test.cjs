const test=require('node:test');const assert=require('node:assert/strict');const fs=require('node:fs');const path=require('node:path');const css=fs.readFileSync(path.join(__dirname,'..','src','index.scss'),'utf8');
test('cards allow text selection',()=>assert.match(css,/\.sw-home-store__card[\s\S]*?user-select: text/));
test('source chips prevent selection',()=>assert.match(css,/\.sw-home-store__source-chip,[\s\S]*?user-select: none/));
test('availability badges prevent selection',()=>assert.match(css,/\.sw-home-store__availability[\s\S]*?user-select: none/));
test('size controls prevent selection',()=>assert.match(css,/\.sw-home-store__sizes,[\s\S]*?user-select: none/));
test('group toggle prevents selection',()=>assert.match(css,/\.sw-home-store__group-toggle[\s\S]*?user-select: none/));
test('clear button prevents selection',()=>assert.match(css,/\.sw-home-store__clear-search[\s\S]*?user-select: none/));
test('selection property standard',()=>assert.match(css,/user-select:/));
test('card keeps focus',()=>assert.match(css,/focus-visible/));
test('card keeps touch',()=>assert.match(css,/touch-action: manipulation/));
test('selection keeps wrapping',()=>assert.match(css,/overflow-wrap: anywhere/));
test('selection keeps word break',()=>assert.match(css,/word-break: break-word/));
test('selection keeps hyphens',()=>assert.match(css,/hyphens: auto/));
test('selection keeps pretty wrapping',()=>assert.match(css,/text-wrap: pretty/));
test('selection keeps mobile',()=>assert.match(css,/max-width: 560px/));
test('selection keeps print',()=>assert.match(css,/@media print/));
test('selection keeps forced colors',()=>assert.match(css,/forced-colors: active/));
test('selection keeps reduced motion',()=>assert.match(css,/prefers-reduced-motion: reduce/));
test('selection keeps isolation',()=>assert.match(css,/isolation: isolate/));
test('selection keeps containment',()=>assert.match(css,/contain: layout paint/));
test('selection no network',()=>assert.doesNotMatch(css,/user-select: text[\s\S]*?url\(/));
test('selection no script',()=>assert.doesNotMatch(css,/user-select: text[\s\S]*?javascript/));
test('card selection scoped',()=>assert.match(css,/sw-home-store__card/));
test('chip selection scoped',()=>assert.match(css,/sw-home-store__source-chip/));
test('badge selection scoped',()=>assert.match(css,/sw-home-store__availability/));
test('control selection scoped',()=>assert.match(css,/sw-home-store__sizes/));
test('selection avoids draggable state',()=>assert.doesNotMatch(css,/user-select: text[\s\S]*?draggable/));
test('selection remains deterministic',()=>assert.ok(css.includes('user-select: text')&&css.includes('user-select: none')));
test('selection card rule closes',()=>assert.match(css,/user-select: text[\s\S]*?\}/));
test('selection control rule closes',()=>assert.match(css,/user-select: none[\s\S]*?\}/));
test('selection contract uses explicit values',()=>assert.match(css,/user-select: (text|none)/));
