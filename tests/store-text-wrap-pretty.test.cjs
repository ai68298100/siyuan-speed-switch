const test=require('node:test');const assert=require('node:assert/strict');const fs=require('node:fs');const path=require('node:path');const css=fs.readFileSync(path.join(__dirname,'..','src','index.scss'),'utf8');
test('pretty wrapping property exists',()=>assert.match(css,/text-wrap: pretty/));
test('title keeps balance fallback',()=>assert.match(css,/text-wrap: balance/));
test('title has pretty wrapping',()=>assert.match(css,/strong[\s\S]*?text-wrap: pretty/));
test('description has pretty wrapping',()=>assert.match(css,/span[\s\S]*?text-wrap: pretty/));
test('status has pretty wrapping',()=>assert.match(css,/\.sw-home-store__status[\s\S]*?text-wrap: pretty/));
test('group has pretty wrapping',()=>assert.match(css,/\.sw-home-store__group[\s\S]*?text-wrap: pretty/));
test('summary text remains wrapped',()=>assert.match(css,/\.sw-home-store__summary[\s\S]*?overflow-wrap: anywhere/));
test('pretty wrapping keeps hyphens',()=>assert.match(css,/hyphens: auto/));
test('pretty wrapping keeps line heights',()=>assert.match(css,/line-height: 1\.35/));
test('pretty wrapping keeps mobile',()=>assert.match(css,/max-width: 560px/));
test('pretty wrapping keeps print',()=>assert.match(css,/@media print/));
test('pretty wrapping keeps high contrast',()=>assert.match(css,/forced-colors: active/));
test('pretty wrapping keeps reduced motion',()=>assert.match(css,/prefers-reduced-motion: reduce/));
test('pretty wrapping is standard CSS',()=>assert.match(css,/text-wrap: pretty/));
test('pretty wrapping avoids network',()=>assert.doesNotMatch(css,/text-wrap: pretty[\s\S]*?url\(/));
test('pretty wrapping avoids scripting',()=>assert.doesNotMatch(css,/text-wrap: pretty[\s\S]*?javascript/));
test('pretty wrapping keeps title block',()=>assert.match(css,/strong[\s\S]*?display: block/));
test('pretty wrapping keeps description clamp',()=>assert.match(css,/-webkit-line-clamp: 2/));
test('pretty wrapping keeps status display',()=>assert.match(css,/\.sw-home-store__status[\s\S]*?display: block/));
test('pretty wrapping keeps group spacing',()=>assert.match(css,/letter-spacing: 0\.04em/));
test('pretty wrapping keeps summary spacing',()=>assert.match(css,/\.sw-home-store__summary[\s\S]*?font-size: 11px/));
test('pretty wrapping keeps font adjust',()=>assert.match(css,/font-size-adjust: from-font/));
test('pretty wrapping keeps numeric style',()=>assert.match(css,/font-variant-numeric: tabular-nums/));
test('pretty wrapping keeps focus',()=>assert.match(css,/focus-visible/));
test('pretty wrapping keeps touch',()=>assert.match(css,/touch-action: manipulation/));
test('pretty wrapping scoped to store',()=>assert.match(css,/sw-home-store__card-head/));
test('pretty wrapping scoped to status',()=>assert.match(css,/sw-home-store__status/));
test('pretty wrapping scoped to group',()=>assert.match(css,/sw-home-store__group/));
test('pretty wrapping deterministic',()=>assert.ok(css.includes('text-wrap: pretty')&&css.includes('text-wrap: balance')));
test('pretty wrapping style closes',()=>assert.match(css,/text-wrap: pretty[\s\S]*?\}/));
