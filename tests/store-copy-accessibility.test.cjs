const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const source = fs.readFileSync(path.join(__dirname, '..', 'src', 'index.ts'), 'utf8');
const zh = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'src', 'i18n', 'zh-CN.json'), 'utf8'));
const en = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'src', 'i18n', 'en.json'), 'utf8'));

test('store title receives stable id', () => assert.match(source, /title\.id = `sw-home-store-title-/));
test('availability badge has aria label', () => assert.match(source, /badge\.setAttribute\("aria-label", badge\.textContent\)/));
test('availability badge has native title', () => assert.match(source, /badge\.title = badge\.textContent/));
test('support text has aria label', () => assert.match(source, /support\.setAttribute\("aria-label", this\.i18n\.homeStoreSupportedSurfaces\)/));
test('source chips have native title', () => assert.match(source, /chip\.title = label/));
test('size tiles have aria labels', () => assert.match(source, /tile\.setAttribute\("aria-label", this\.i18n\.homeStoreSizeHint/));
test('config button has native title', () => assert.match(source, /configButton\.title = configButton\.getAttribute\("aria-label"\)/));
test('remove button has aria label', () => assert.match(source, /removeButton\.setAttribute\("aria-label"/));
test('preview button has native title', () => assert.match(source, /previewButton\.title = previewButton\.getAttribute\("aria-label"\)/));
test('size hint has Chinese translation', () => assert.equal(zh.homeStoreSizeHint, '选择尺寸：{size}'));
test('size hint has English translation', () => assert.equal(en.homeStoreSizeHint, 'Choose size: {size}'));
test('size hint preserves placeholder', () => assert.ok(zh.homeStoreSizeHint.includes('{size}') && en.homeStoreSizeHint.includes('{size}')));
test('title ids are module scoped', () => assert.match(source, /sw-home-store-title-\$\{moduleId\}/));
test('availability copy remains localized', () => assert.match(source, /homeStoreAvailabilityExternal/));
test('conditional copy remains localized', () => assert.match(source, /homeStoreAvailabilityConditional/));
test('surface copy remains localized', () => assert.match(source, /homeStoreSupportedSurfaces/));
test('size copy remains localized', () => assert.match(source, /homeStoreSizeHint/));
test('config copy includes component title', () => assert.match(source, /homeConfig} · \$\{def\.title/));
test('remove copy includes component title', () => assert.match(source, /homeStoreRemove} · \$\{def\.title/));
test('preview copy includes component title', () => assert.match(source, /homeStorePreview} · \$\{def\.title/));
test('source chip title uses rendered label', () => assert.match(source, /chip\.textContent = label/));
test('size tile label uses rendered text', () => assert.match(source, /tile\.textContent = HOME_WIDGET_SIZE_LABELS/));
test('support aria remains stable across surfaces', () => assert.match(source, /supportedDevices\.map/));
test('title id does not expose config values', () => assert.doesNotMatch(source, /title\.id = .*config/));
test('native titles remain bounded to visible labels', () => assert.match(source, /title = .*textContent/));
test('remove action remains a button', () => assert.match(source, /removeButton\.type = "button"/));
test('config action remains a button', () => assert.match(source, /configButton\.type = "button"/));
test('preview action remains a button', () => assert.match(source, /previewButton\.className/));
test('size hint is referenced from runtime', () => assert.match(source, /homeStoreSizeHint\.replace/));
test('aria labels use component title fallback', () => assert.match(source, /def\.title \|\| moduleId/));
