const test=require('node:test');const assert=require('node:assert/strict');const fs=require('node:fs');const path=require('node:path');const css=fs.readFileSync(path.join(__dirname,'..','src','index.scss'),'utf8');
const cardHeadBlock=(css.match(/\.sw-home-store__card-head\s*\{([\s\S]*?)\n\}\s*\n\s*\.sw__home-source-health/ )||[])[1]||'';
test('card title wraps anywhere',()=>assert.match(css,/strong[\s\S]*?overflow-wrap: anywhere/));
test('card title balances text',()=>assert.match(css,/text-wrap: balance/));
test('card descriptions wrap anywhere',()=>assert.match(css,/span[\s\S]*?overflow-wrap: anywhere/));
test('group labels wrap anywhere',()=>assert.match(css,/\.sw-home-store__group[\s\S]*?overflow-wrap: anywhere/));
test('group labels balance text',()=>assert.match(css,/\.sw-home-store__group[\s\S]*?text-wrap: balance/));
test('summary wraps anywhere',()=>assert.match(css,/\.sw-home-store__summary[\s\S]*?overflow-wrap: anywhere/));
test('title remains block',()=>assert.match(css,/strong \{[\s\S]*?display: block/));
test('description remains clamped',()=>assert.match(css,/-webkit-line-clamp: 2/));
test('description remains hidden overflow',()=>assert.match(css,/span \{[\s\S]*?overflow: hidden/));
test('typography is scoped to store card',()=>assert.match(css,/sw-home-store__card-head/));
test('group typography is scoped',()=>assert.match(css,/sw-home-store__group/));
test('summary typography is scoped',()=>assert.match(css,/sw-home-store__summary/));
test('title typography supports unicode',()=>assert.match(css,/overflow-wrap: anywhere/));
test('description typography supports long URLs',()=>assert.match(css,/overflow-wrap: anywhere/));
test('group typography supports long labels',()=>assert.match(css,/text-wrap: balance/));
test('summary remains bounded',()=>assert.match(css,/min-height: 18px/));
test('card title retains font size',()=>assert.match(css,/font-size: 13px/));
test('card description retains font size',()=>assert.match(css,/font-size: 12px/));
test('support text retains font size',()=>assert.match(css,/font-size: 11px/));
test('group label retains font size',()=>assert.match(css,/font-size: 12px/));
test('summary retains font size',()=>assert.match(css,/\.sw-home-store__summary[\s\S]*?font-size: 11px/));
test('typography avoids fixed width',()=>assert.doesNotMatch(cardHeadBlock,/text-wrap: balance[\s\S]*?width: [0-9]+px/));
test('typography preserves balanced wrapping',()=>assert.match(css,/text-wrap: balance/));
test('typography preserves mobile media',()=>assert.match(css,/max-width: 560px/));
test('typography preserves focus states',()=>assert.match(css,/focus-visible/));
test('typography preserves touch states',()=>assert.match(css,/touch-action: manipulation/));
test('typography uses standard wrap property',()=>assert.match(css,/overflow-wrap: anywhere/));
test('typography uses standard balance property',()=>assert.match(css,/text-wrap: balance/));
test('typography has no network dependency',()=>assert.doesNotMatch(css,/text-wrap: balance[\s\S]*?url\(/));
test('typography contract deterministic',()=>assert.ok(css.includes('overflow-wrap: anywhere')&&css.includes('text-wrap: balance')));
test('typography CSS remains closed',()=>assert.match(css,/text-wrap: balance[\s\S]*?\}/));
