test('hyphenation is card scoped',()=>assert.match(css,/sw-home-store__card-head/));
test('hyphenation is group scoped',()=>assert.match(css,/sw-home-store__group/));
test('hyphenation is summary scoped',()=>assert.match(css,/sw-home-store__summary/));
test('hyphenation remains mobile compatible',()=>assert.match(css,/max-width: 560px/));
test('hyphenation preserves focus rules',()=>assert.match(css,/focus-visible/));
