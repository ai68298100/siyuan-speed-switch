const test=require('node:test');const assert=require('node:assert/strict');const fs=require('node:fs');const path=require('node:path');const css=fs.readFileSync(path.join(__dirname,'..','src','index.scss'),'utf8');
test('store grid isolates stacking',()=>assert.match(css,/\.sw-home-store__grid[\s\S]*?isolation: isolate/));
test('store card isolates stacking',()=>assert.match(css,/\.sw-home-store__card[\s\S]*?isolation: isolate/));
test('source metadata is positioned',()=>assert.match(css,/\.sw-home-store__source-meta[\s\S]*?position: relative/));
test('source metadata has z index',()=>assert.match(css,/\.sw-home-store__source-meta[\s\S]*?z-index: 1/));
test('grid keeps overscroll',()=>assert.match(css,/overscroll-behavior: contain/));
test('card keeps border box',()=>assert.match(css,/box-sizing: border-box/));
test('stacking preserves focus',()=>assert.match(css,/focus-visible/));
test('stacking preserves hover',()=>assert.match(css,/&:hover/));
test('stacking preserves mobile',()=>assert.match(css,/max-width: 560px/));
test('stacking preserves print',()=>assert.match(css,/@media print/));
test('stacking preserves forced colors',()=>assert.match(css,/forced-colors: active/));
test('stacking preserves reduced motion',()=>assert.match(css,/prefers-reduced-motion: reduce/));
test('isolation is standard',()=>assert.match(css,/isolation: isolate/));
test('position is standard',()=>assert.match(css,/position: relative/));
test('z index is bounded',()=>assert.match(css,/z-index: 1/));
test('stacking avoids giant z index',()=>assert.doesNotMatch(css,/source-meta[\s\S]*?z-index: 2147483647/));
test('stacking avoids network',()=>assert.doesNotMatch(css,/isolation: isolate[\s\S]*?url\(/));
test('stacking avoids script',()=>assert.doesNotMatch(css,/isolation: isolate[\s\S]*?javascript/));
test('grid scope remains',()=>assert.match(css,/sw-home-store__grid/));
test('card scope remains',()=>assert.match(css,/sw-home-store__card/));
test('metadata scope remains',()=>assert.match(css,/sw-home-store__source-meta/));
test('stacking keeps content visibility',()=>assert.match(css,/content-visibility: auto/));
test('stacking keeps intrinsic size',()=>assert.match(css,/contain-intrinsic-size/));
test('stacking keeps typography',()=>assert.match(css,/font-size-adjust: from-font/));
test('stacking keeps wrapping',()=>assert.match(css,/word-break: break-word/));
test('stacking keeps touch',()=>assert.match(css,/touch-action: manipulation/));
test('stacking uses one metadata z index',()=>assert.match(css,/source-meta[\s\S]*?z-index: 1/));
test('grid isolation deterministic',()=>assert.ok(css.includes('sw-home-store__grid')&&css.includes('isolation: isolate')));
test('card isolation deterministic',()=>assert.ok(css.includes('sw-home-store__card')&&css.includes('isolation: isolate')));
test('stacking contract closes',()=>assert.match(css,/isolation: isolate[\s\S]*?\}/));
