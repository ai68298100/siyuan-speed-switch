const test=require('node:test');const assert=require('node:assert/strict');const fs=require('node:fs');const path=require('node:path');const css=fs.readFileSync(path.join(__dirname,'..','src','index.scss'),'utf8');
test('title uses font size adjust',()=>assert.match(css,/strong[\s\S]*?font-size-adjust: from-font/));
test('description uses font size adjust',()=>assert.match(css,/span[\s\S]*?font-size-adjust: from-font/));
test('source chip uses font size adjust',()=>assert.match(css,/\.sw-home-store__source-chip,[\s\S]*?font-size-adjust: from-font/));
test('availability uses font size adjust',()=>assert.match(css,/\.sw-home-store__availability[\s\S]*?font-size-adjust: from-font/));
test('title uses compact letter spacing',()=>assert.match(css,/strong[\s\S]*?letter-spacing: -0\.01em/));
test('status uses readable letter spacing',()=>assert.match(css,/\.sw-home-store__status[\s\S]*?letter-spacing: 0\.01em/));
test('font adjust uses from-font',()=>assert.match(css,/font-size-adjust: from-font/));
test('metrics remain card scoped',()=>assert.match(css,/sw-home-store__card-head/));
test('status remains scoped',()=>assert.match(css,/sw-home-store__status/));
test('source remains scoped',()=>assert.match(css,/sw-home-store__source-chip/));
test('availability remains scoped',()=>assert.match(css,/sw-home-store__availability/));
test('title remains block',()=>assert.match(css,/strong \{[\s\S]*?display: block/));
test('description remains clamped',()=>assert.match(css,/-webkit-line-clamp: 2/));
test('metrics preserve wrapping',()=>assert.match(css,/overflow-wrap: anywhere/));
test('metrics preserve hyphenation',()=>assert.match(css,/hyphens: auto/));
test('metrics preserve balancing',()=>assert.match(css,/text-wrap: balance/));
test('metrics preserve mobile',()=>assert.match(css,/max-width: 560px/));
test('metrics preserve print',()=>assert.match(css,/@media print/));
test('metrics preserve forced colors',()=>assert.match(css,/forced-colors: active/));
test('metrics preserve reduced motion',()=>assert.match(css,/prefers-reduced-motion: reduce/));
test('metrics avoid fixed width',()=>assert.match(css,/font-size-adjust: from-font/));
test('metrics no network url',()=>assert.doesNotMatch(css,/font-size-adjust: from-font[\s\S]*?url\(/));
test('metrics no script',()=>assert.doesNotMatch(css,/font-size-adjust: from-font[\s\S]*?javascript/));
test('metrics standard property',()=>assert.match(css,/font-size-adjust/));
test('metrics standard spacing',()=>assert.match(css,/letter-spacing/));
test('metrics preserve theme text',()=>assert.match(css,/var\(--b3-theme-on-surface-light\)/));
test('metrics preserve status accent',()=>assert.match(css,/is-added/));
test('metrics title rule closes',()=>assert.match(css,/font-size-adjust: from-font[\s\S]*?\}/));
test('metrics status rule closes',()=>assert.match(css,/letter-spacing: 0\.01em[\s\S]*?\}/));
test('metrics deterministic',()=>assert.ok(css.includes('font-size-adjust: from-font')&&css.includes('letter-spacing')));
