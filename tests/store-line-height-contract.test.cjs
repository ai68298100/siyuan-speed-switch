const test=require('node:test');const assert=require('node:assert/strict');const fs=require('node:fs');const path=require('node:path');const css=fs.readFileSync(path.join(__dirname,'..','src','index.scss'),'utf8');
test('title line height is defined',()=>assert.match(css,/strong[\s\S]*?line-height: 1\.35/));
test('description line height is defined',()=>assert.match(css,/span[\s\S]*?line-height: 1\.45/));
test('status line height is defined',()=>assert.match(css,/\.sw-home-store__status[\s\S]*?line-height: 1\.35/));
test('group line height is defined',()=>assert.match(css,/\.sw-home-store__group[\s\S]*?line-height: 1\.35/));
test('summary line height is defined',()=>assert.match(css,/\.sw-home-store__summary[\s\S]*?line-height: 1\.45/));
test('title retains font size',()=>assert.match(css,/strong[\s\S]*?font-size: 13px/));
test('description retains font size',()=>assert.match(css,/font-size: 12px/));
test('status retains font size',()=>assert.match(css,/\.sw-home-store__status[\s\S]*?font-size: 11px/));
test('group retains font size',()=>assert.match(css,/\.sw-home-store__group[\s\S]*?font-size: 12px/));
test('summary retains font size',()=>assert.match(css,/\.sw-home-store__summary[\s\S]*?font-size: 11px/));
test('line height uses unitless values',()=>assert.match(css,/line-height: 1\.35/));
test('line height avoids px lock',()=>assert.doesNotMatch(css,/line-height: 1\.35;\s*height:/));
test('line height preserves wrapping',()=>assert.match(css,/overflow-wrap: anywhere/));
test('line height preserves hyphens',()=>assert.match(css,/hyphens: auto/));
test('line height preserves balancing',()=>assert.match(css,/text-wrap: balance/));
test('line height preserves mobile',()=>assert.match(css,/max-width: 560px/));
test('line height preserves print',()=>assert.match(css,/@media print/));
test('line height preserves forced colors',()=>assert.match(css,/forced-colors: active/));
test('line height preserves reduced motion',()=>assert.match(css,/prefers-reduced-motion: reduce/));
test('line height title scoped',()=>assert.match(css,/sw-home-store__card-head/));
test('line height status scoped',()=>assert.match(css,/sw-home-store__status/));
test('line height group scoped',()=>assert.match(css,/sw-home-store__group/));
test('line height summary scoped',()=>assert.match(css,/sw-home-store__summary/));
test('line height no network',()=>assert.doesNotMatch(css,/line-height: 1\.45[\s\S]*?url\(/));
test('line height no script',()=>assert.doesNotMatch(css,/line-height: 1\.45[\s\S]*?javascript/));
test('line height standard property',()=>assert.match(css,/line-height/));
test('line height title rule closes',()=>assert.match(css,/strong[\s\S]*?line-height: 1\.35[\s\S]*?\}/));
test('line height status rule closes',()=>assert.match(css,/\.sw-home-store__status[\s\S]*?line-height: 1\.35[\s\S]*?\}/));
test('line height summary rule closes',()=>assert.match(css,/\.sw-home-store__summary[\s\S]*?line-height: 1\.45[\s\S]*?\}/));
test('line height contract deterministic',()=>assert.ok(css.includes('line-height: 1.35')&&css.includes('line-height: 1.45')));
