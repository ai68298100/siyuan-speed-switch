const test=require('node:test');const assert=require('node:assert/strict');const fs=require('node:fs');const path=require('node:path');const css=fs.readFileSync(path.join(__dirname,'..','src','index.scss'),'utf8');
test('card uses border box',()=>assert.match(css,/\.sw-home-store__card[\s\S]*?box-sizing: border-box/));
test('status uses border box',()=>assert.match(css,/\.sw-home-store__status[\s\S]*?box-sizing: border-box/));
test('group uses border box',()=>assert.match(css,/\.sw-home-store__group[\s\S]*?box-sizing: border-box/));
test('summary uses border box',()=>assert.match(css,/\.sw-home-store__summary[\s\S]*?box-sizing: border-box/));
test('card keeps min width zero',()=>assert.match(css,/\.sw-home-store__card[\s\S]*?min-width: 0/));
test('card keeps max width full',()=>assert.match(css,/\.sw-home-store__card[\s\S]*?max-width: 100%/));
test('status keeps min width zero',()=>assert.match(css,/\.sw-home-store__status[\s\S]*?min-width: 0/));
test('group keeps min width zero',()=>assert.match(css,/\.sw-home-store__group[\s\S]*?min-width: 0/));
test('summary keeps min width zero',()=>assert.match(css,/\.sw-home-store__summary[\s\S]*?min-width: 0/));
test('box sizing preserves wrapping',()=>assert.match(css,/overflow-wrap: anywhere/));
test('box sizing preserves word break',()=>assert.match(css,/word-break: break-word/));
test('box sizing preserves hyphens',()=>assert.match(css,/hyphens: auto/));
test('box sizing preserves line height',()=>assert.match(css,/line-height: 1\.35/));
test('box sizing preserves mobile',()=>assert.match(css,/max-width: 560px/));
test('box sizing preserves print',()=>assert.match(css,/@media print/));
test('box sizing preserves forced colors',()=>assert.match(css,/forced-colors: active/));
test('box sizing preserves reduced motion',()=>assert.match(css,/prefers-reduced-motion: reduce/));
test('box sizing is standard',()=>assert.match(css,/box-sizing: border-box/));
test('box sizing avoids content box',()=>assert.doesNotMatch(css,/sw-home-store__card[\s\S]*?box-sizing: content-box/));
test('card scope remains',()=>assert.match(css,/sw-home-store__card/));
test('status scope remains',()=>assert.match(css,/sw-home-store__status/));
test('group scope remains',()=>assert.match(css,/sw-home-store__group/));
test('summary scope remains',()=>assert.match(css,/sw-home-store__summary/));
test('box sizing no network',()=>assert.doesNotMatch(css,/box-sizing: border-box[\s\S]*?url\(/));
test('box sizing no script',()=>assert.doesNotMatch(css,/box-sizing: border-box[\s\S]*?javascript/));
test('box sizing keeps focus',()=>assert.match(css,/focus-visible/));
test('box sizing keeps touch',()=>assert.match(css,/touch-action: manipulation/));
test('box sizing keeps content visibility',()=>assert.match(css,/content-visibility: auto/));
test('box sizing keeps intrinsic size',()=>assert.match(css,/contain-intrinsic-size/));
test('box sizing deterministic',()=>assert.ok(css.includes('box-sizing: border-box')&&css.includes('min-width: 0')));
